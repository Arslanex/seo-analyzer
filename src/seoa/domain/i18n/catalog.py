_ENTRIES.extend(_APP_ENTRIES)

CATALOG: dict[str, dict[str, str]] = {"tr": {}, "en": {}}
for _k, _tr, _en in _ENTRIES:
    if _k in CATALOG["tr"]:
        raise ValueError(f"duplicate i18n key {_k}")
    CATALOG["tr"][_k] = _tr
    CATALOG["en"][_k] = _en


def norm_lang(lang: str | None) -> str:
    return lang if lang in LANGS else DEFAULT_LANG


def t(lang: str, key: str, **params: object) -> str:
    """Translate. Unknown key -> the key itself (never raises, never leaks)."""
    text = CATALOG.get(norm_lang(lang), {}).get(key)
    if text is None:
        text = CATALOG["en"].get(key, key)
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def reason_text(lang: str, code: str | None) -> str:
    """Sentence for a reason code; non-code free text is returned unchanged."""
    if not code:
        return t(lang, "reason.unknown")
    key = f"reason.{code}"
    if key in CATALOG["en"]:
        return t(lang, key)
    return code


def missing_keys(catalog: Mapping[str, Mapping[str, str]] = CATALOG) -> set[str]:
    return set(catalog["tr"]) ^ set(catalog["en"])
